// 生成极简静态文档站到 site/：卡片索引页，每篇 docs/*.md 取首个一级标题作描述，
// 链接指向 GitHub blob 视图（自带 md 渲染，零转换依赖）。
// 用法：node scripts/build-docs-site.mjs
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const docsDir = resolve(root, 'docs')
const repo = 'ZunbaRan/dsh-openloop'
const branch = 'main'

const files = readdirSync(docsDir)
  .filter(f => f.endsWith('.md'))
  .sort()

const cards = files.map((file) => {
  const text = readFileSync(resolve(docsDir, file), 'utf8')
  // 首个非 frontmatter 的 # 标题；没有则用文件名
  const h1 = (text.match(/^#\s+(.+)$/m) || [])[1] || file
  // 标题后第一段非空文本作摘要（截断 120 字）
  const body = text.slice(text.indexOf(h1) + h1.length)
  const firstLine = (body.split('\n').map(s => s.trim()).find(s => s && !s.startsWith('#') && !s.startsWith('>')) || '').replace(/[*`>|]/g, '')
  const desc = firstLine.length > 120 ? firstLine.slice(0, 120) + '…' : firstLine
  return { file, h1, desc, url: `https://github.com/${repo}/blob/${branch}/docs/${encodeURIComponent(file)}` }
})

const html = `<!DOCTYPE html>
<html lang="zh-CN">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>dsh-openloop · 设计文档</title>
<style>
  :root { color-scheme: dark; }
  * { box-sizing: border-box; margin: 0; }
  body {
    font-family: -apple-system, "SF Pro Text", "PingFang SC", sans-serif;
    background: #0d1117; color: #e6edf3; min-height: 100vh;
    display: flex; justify-content: center; padding: 64px 24px;
  }
  main { max-width: 880px; width: 100%; }
  .eyebrow { color: #7d8590; font-size: 13px; letter-spacing: .12em; text-transform: uppercase; }
  h1 { font-size: 34px; margin: 8px 0 12px; }
  .sub { color: #9198a1; margin-bottom: 40px; line-height: 1.7; }
  .sub a { color: #58a6ff; text-decoration: none; }
  .grid { display: grid; grid-template-columns: repeat(auto-fill, minmax(260px, 1fr)); gap: 16px; }
  a.card {
    display: block; padding: 20px; border: 1px solid #21262d; border-radius: 12px;
    background: #161b22; text-decoration: none; color: inherit;
    transition: border-color .15s, transform .15s;
  }
  a.card:hover { border-color: #58a6ff; transform: translateY(-2px); }
  .card .file { color: #7d8590; font-size: 12px; font-family: ui-monospace, monospace; margin-bottom: 6px; }
  .card h2 { font-size: 16px; margin-bottom: 8px; color: #e6edf3; }
  .card p { font-size: 13px; color: #9198a1; line-height: 1.6; }
  footer { margin-top: 48px; color: #484f58; font-size: 12px; font-family: ui-monospace, monospace; }
</style>
</head>
<body>
<main>
  <div class="eyebrow">OpenLoop</div>
  <h1>设计文档</h1>
  <p class="sub">DSH 插件生态实验场 —— 把 DeepSeek Harness 改造成 Agent Native 产品底座。
  源码见 <a href="https://github.com/${repo}">${repo}</a>，本页由 GitHub Actions 自动部署。</p>
  <div class="grid">
${cards.map(c => `    <a class="card" href="${c.url}">
      <div class="file">docs/${c.file}</div>
      <h2>${c.h1}</h2>
      <p>${c.desc || '（无摘要）'}</p>
    </a>`).join('\n')}
  </div>
  <footer>generated by scripts/build-docs-site.mjs · ${new Date().toISOString()}</footer>
</main>
</body>
</html>
`

const siteDir = resolve(root, 'site')
mkdirSync(siteDir, { recursive: true })
writeFileSync(resolve(siteDir, 'index.html'), html)
console.log(`site/index.html 已生成（${cards.length} 篇文档卡片）`)
